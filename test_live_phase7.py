import asyncio
import time
import httpx

REQUIRED_SECTIONS = [
    "## Ringkasan",
    "## Tren Kesehatan",
    "## Aktivitas & Tidur",
    "## Kepatuhan Obat",
    "## Kejadian Penting",
    "## Hal yang Perlu Diperhatikan",
    "## Saran untuk Keluarga",
]

DISCLAIMER = "*Laporan ini dibuat otomatis dari data pemantauan dan bukan pengganti pemeriksaan dokter.*"

async def main():
    async with httpx.AsyncClient(base_url="http://127.0.0.1:8000", timeout=30.0) as client:
        # 1. Login Caregiver
        res = await client.post("/auth/login", json={"email": "caregiver@demo.id", "password": "demo1234"})
        assert res.status_code == 200
        token = res.json()["access_token"]
        headers = {"Authorization": f"Bearer {token}"}

        # 2. Get Pak Budi ID
        res = await client.get("/me", headers=headers)
        budi_id = next(e["id"] for e in res.json()["elders"] if "Budi" in e["name"])
        print(f"Testing Phase 7 Smart Report on Pak Budi ({budi_id})...")

        # 3. Generate Report (Acceptance check: under 15 s)
        t0 = time.time()
        res = await client.post(f"/elders/{budi_id}/reports/generate?days=7", headers=headers)
        duration = time.time() - t0
        print(f"POST /reports/generate completed in {duration:.2f}s (status: {res.status_code})")
        assert res.status_code == 201, res.text
        assert duration < 15.0, f"Report generation exceeded 15s: took {duration}s"

        report_data = res.json()
        report_id = report_data["id"]
        content_md = report_data["content_md"]
        generated_by = report_data["generated_by"]
        print(f"Generated by: {generated_by}")
        print("\nReport Content Preview:\n" + content_md[:500] + "\n...\n")

        # 4. Verify all 7 required sections
        for sec in REQUIRED_SECTIONS:
            assert sec in content_md, f"Missing required section: {sec}"
        print("All 7 required Markdown sections present!")

        # 5. Verify mandatory medical disclaimer
        assert DISCLAIMER in content_md, "Mandatory disclaimer missing from report!"
        print("Mandatory medical disclaimer verified!")

        # 6. Verify stats_json is present and complete
        stats = report_data["stats_json"]
        assert "heart_rate" in stats
        assert "blood_pressure" in stats
        assert "glucose" in stats
        assert "medication" in stats
        assert "activity" in stats
        print("Aggregated stats verified!")

        # 7. List reports
        res = await client.get(f"/elders/{budi_id}/reports", headers=headers)
        print("GET /elders/{id}/reports count:", len(res.json()))
        assert res.status_code == 200
        assert any(r["id"] == report_id for r in res.json())

        # 8. Get report detail
        res = await client.get(f"/reports/{report_id}", headers=headers)
        assert res.status_code == 200
        assert res.json()["id"] == report_id
        assert res.json()["content_md"] == content_md
        print("GET /reports/{id} verified!")

        print("\n=== PHASE 7 ACCEPTANCE CHECK PASSED! ===")

if __name__ == "__main__":
    asyncio.run(main())
